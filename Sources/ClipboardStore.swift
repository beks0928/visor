import AppKit
import Observation

enum ClipKind: String, Codable, Sendable {
    case text, link, color
}

struct ClipItem: Identifiable, Codable, Equatable, Sendable {
    let id: UUID
    var text: String
    var kind: ClipKind
    var pinned: Bool
    var date: Date
}

struct Snippet: Identifiable, Codable, Equatable, Sendable {
    let id: UUID
    var title: String
    var text: String
    /// Закреплённые сниппеты стоят в списке первыми.
    var pinned: Bool

    init(id: UUID, title: String, text: String, pinned: Bool = false) {
        self.id = id
        self.title = title
        self.text = text
        self.pinned = pinned
    }

    /// Файлы, написанные руками или прежней версией, могут быть без поля `pinned`.
    init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        id = try container.decode(UUID.self, forKey: .id)
        title = try container.decode(String.self, forKey: .title)
        text = try container.decode(String.self, forKey: .text)
        pinned = try container.decodeIfPresent(Bool.self, forKey: .pinned) ?? false
    }
}

enum ColorFormat: String, CaseIterable, Identifiable, Sendable {
    case hex, rgb, swiftUI

    var id: String { rawValue }

    var title: String {
        switch self {
        case .hex: "HEX"
        case .rgb: "RGB"
        case .swiftUI: "SwiftUI"
        }
    }
}

/// Цвет в виде, в котором его копируют: `#5B8CFF`, `rgb(91, 140, 255)` или `Color(red: …)`.
enum ClipColor {
    static func parse(_ text: String) -> (r: Int, g: Int, b: Int)? {
        let value = text.trimmingCharacters(in: .whitespaces)
        if value.hasPrefix("#"), value.count == 7, let number = Int(value.dropFirst(), radix: 16) {
            return (number >> 16 & 255, number >> 8 & 255, number & 255)
        }
        if value.lowercased().hasPrefix("rgb("), value.hasSuffix(")") {
            let parts = value.dropFirst(4).dropLast().split(separator: ",").compactMap { Int($0.trimmingCharacters(in: .whitespaces)) }
            if parts.count == 3, parts.allSatisfy({ (0...255).contains($0) }) { return (parts[0], parts[1], parts[2]) }
        }
        return nil
    }

    static func format(_ color: (r: Int, g: Int, b: Int), as format: ColorFormat) -> String {
        switch format {
        case .hex:
            return String(format: "#%02X%02X%02X", color.r, color.g, color.b)
        case .rgb:
            return "rgb(\(color.r), \(color.g), \(color.b))"
        case .swiftUI:
            func part(_ v: Int) -> String { String(format: "%.3f", Double(v) / 255) }
            return "Color(red: \(part(color.r)), green: \(part(color.g)), blue: \(part(color.b)))"
        }
    }
}

/// Буфер обмена: последние 40 копирований, закрепы, сниппеты и пипетка цвета.
/// История держится только в памяти: в буфере бывают пароли. На диск идут закреплённое и сниппеты.
@MainActor @Observable
final class ClipboardStore {
    static let shared = ClipboardStore(pasteboard: .general, directory: VisorPaths.supportDir)

    private(set) var items: [ClipItem] = []
    private(set) var snippets: [Snippet] = []
    private(set) var colorFormat: ColorFormat
    /// Короткое подтверждение рядом с заголовком, например «Скопировано».
    private(set) var flash: String?
    private(set) var isPicking = false

    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private let directory: URL
    @ObservationIgnored private var lastChange: Int
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var sampler: NSColorSampler?
    @ObservationIgnored private var flashTask: Task<Void, Never>?

    static let limit = 40
    private static let maxLength = 20000
    /// Пометки, которыми менеджеры паролей отмечают то, что нельзя запоминать.
    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    init(pasteboard: NSPasteboard, directory: URL) {
        self.pasteboard = pasteboard
        self.directory = directory
        lastChange = pasteboard.changeCount
        colorFormat = ColorFormat(rawValue: UserDefaults.standard.string(forKey: "clipboard.colorFormat") ?? "") ?? .hex
        loadPinned()
        loadSnippets()
    }

    private var clipboardURL: URL { directory.appendingPathComponent("clipboard.json") }
    private var snippetsURL: URL { directory.appendingPathComponent("snippets.json") }

    // MARK: Слежение за буфером

    /// Раз в 0,7 секунды сравнивается счётчик буфера. Это единственная фоновая работа вкладки.
    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    func poll() {
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        if let types = pasteboard.types, types.contains(where: { Self.secretTypes.contains($0.rawValue) }) { return }
        guard let text = pasteboard.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty, text.count <= Self.maxLength else { return }
        record(text)
    }

    func record(_ text: String) {
        let kind = Self.kind(of: text)
        if let index = items.firstIndex(where: { $0.text == text }) {
            var item = items.remove(at: index)
            item.date = Date()
            items.insert(item, at: 0)
        } else {
            items.insert(ClipItem(id: UUID(), text: text, kind: kind, pinned: false, date: Date()), at: 0)
        }
        // Закреплённые не вытесняются: лимит считается только по остальным.
        var unpinned = 0
        items.removeAll { item in
            guard !item.pinned else { return false }
            unpinned += 1
            return unpinned > Self.limit
        }
        savePinned()
    }

    static func kind(of text: String) -> ClipKind {
        if ClipColor.parse(text) != nil { return .color }
        if let url = URL(string: text), ["http", "https"].contains(url.scheme?.lowercased() ?? ""), url.host != nil, !text.contains(" ") {
            return .link
        }
        return .text
    }

    // MARK: Действия

    /// Кладёт запись обратно в буфер. Цвет копируется в выбранном формате.
    func copy(_ item: ClipItem) {
        var text = item.text
        if item.kind == .color, let color = ClipColor.parse(item.text) { text = ClipColor.format(color, as: colorFormat) }
        write(text)
        showFlash("Скопировано")
    }

    /// Кладёт обычный текст в буфер и в историю: так копируются результаты инструментов.
    func copyPlain(_ text: String) {
        write(text)
        record(text)
    }

    private func write(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChange = pasteboard.changeCount // свою запись заново не запоминаем
    }

    func togglePin(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].pinned.toggle()
        savePinned()
    }

    func remove(_ id: UUID) {
        items.removeAll { $0.id == id }
        savePinned()
    }

    func clearUnpinned() {
        items.removeAll { !$0.pinned }
    }

    func setColorFormat(_ format: ColorFormat) {
        colorFormat = format
        UserDefaults.standard.set(format.rawValue, forKey: "clipboard.colorFormat")
    }

    private func showFlash(_ text: String) {
        flash = text
        flashTask?.cancel()
        flashTask = Task { [weak self] in
            try? await Task.sleep(for: .seconds(1.4))
            guard !Task.isCancelled else { return }
            self?.flash = nil
        }
    }

    // MARK: Пипетка

    /// Системная пипетка: цвет берётся с любого места экрана и попадает в историю и в буфер.
    func pickColor() {
        guard !isPicking else { return }
        isPicking = true
        let sampler = NSColorSampler()
        self.sampler = sampler
        sampler.show { color in
            var rgb: [Int]?
            if let c = color?.usingColorSpace(.sRGB) {
                rgb = [Int((c.redComponent * 255).rounded()), Int((c.greenComponent * 255).rounded()), Int((c.blueComponent * 255).rounded())]
            }
            Task { @MainActor [weak self] in
                self?.isPicking = false
                self?.sampler = nil
                guard let rgb else { return }
                self?.addPicked((rgb[0], rgb[1], rgb[2]))
            }
        }
    }

    func addPicked(_ rgb: (Int, Int, Int)) {
        let hex = ClipColor.format((rgb.0, rgb.1, rgb.2), as: .hex)
        record(hex)
        if let item = items.first(where: { $0.text == hex }) { copy(item) }
    }

    // MARK: Сниппеты

    @discardableResult
    func addSnippet(title: String, text: String) -> Bool {
        let cleanTitle = title.trimmingCharacters(in: .whitespacesAndNewlines)
        let cleanText = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !cleanText.isEmpty, !snippets.contains(where: { $0.text == cleanText }) else { return false }
        snippets.append(Snippet(id: UUID(), title: cleanTitle.isEmpty ? String(cleanText.prefix(20)) : cleanTitle, text: cleanText))
        saveSnippets()
        return true
    }

    /// Запись из истории становится сниппетом: остаётся в списке, даже когда история вытеснит её.
    func saveAsSnippet(_ item: ClipItem) {
        let added = addSnippet(title: "", text: item.text)
        showFlash(added ? "Добавлено в сниппеты" : "Уже в сниппетах")
    }

    /// Закреплённые первыми, внутри групп порядок добавления.
    var orderedSnippets: [Snippet] {
        snippets.filter(\.pinned) + snippets.filter { !$0.pinned }
    }

    func toggleSnippetPin(_ id: UUID) {
        guard let index = snippets.firstIndex(where: { $0.id == id }) else { return }
        snippets[index].pinned.toggle()
        saveSnippets()
    }

    func removeSnippet(_ id: UUID) {
        snippets.removeAll { $0.id == id }
        saveSnippets()
    }

    func copy(_ snippet: Snippet) {
        write(snippet.text)
        showFlash("Скопировано: \(snippet.title)")
    }

    /// Сниппеты можно править руками в snippets.json: файл перечитывается при открытии вкладки.
    func reloadSnippets() { loadSnippets() }

    // MARK: Хранение

    private func loadPinned() {
        guard let data = try? Data(contentsOf: clipboardURL) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        items = ((try? decoder.decode([ClipItem].self, from: data)) ?? []).filter(\.pinned)
    }

    private func savePinned() {
        write(json: items.filter(\.pinned), to: clipboardURL)
    }

    private func loadSnippets() {
        guard let data = try? Data(contentsOf: snippetsURL) else { return }
        if let decoded = try? JSONDecoder().decode([Snippet].self, from: data) { snippets = decoded }
    }

    private func saveSnippets() {
        write(json: snippets, to: snippetsURL)
    }

    private func write<T: Encodable>(json value: T, to url: URL) {
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        guard let data = try? encoder.encode(value) else { return }
        try? data.write(to: url, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}
